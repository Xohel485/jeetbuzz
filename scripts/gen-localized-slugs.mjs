/**
 * Generates src/lib/localized-slugs.ts from the LOCALIZED_ROUTES registry.
 *
 * hreflang alternates must only point at URLs that actually return 200.
 * The localized splat route (/{country}/{lang}/{slug}) serves a slug only
 * when the registry contains it and the optional `countries` gate allows
 * that country. This script mirrors that gate into a dependency-free data
 * module so schema.ts can build accurate clusters without importing the
 * registry (which pulls in every route component).
 *
 * Run: bun scripts/gen-localized-slugs.mjs
 */
import { readFileSync, writeFileSync } from "node:fs";

const src = readFileSync("src/lib/localized-routes.ts", "utf8");
const chunks = src.split(/entry\(/).slice(1);
const map = {};
for (const chunk of chunks) {
  const slugMatch = chunk.match(/^\s*"([^"]*)"/);
  if (!slugMatch) continue;
  const slug = slugMatch[1];
  // The closing arg list of an entry looks like:  }, ["bd"]),
  const gate = chunk.match(/\}\s*,\s*\[([^\]]*)\]\s*\)/);
  const countries = gate
    ? gate[1].match(/"([a-z]{2})"/g)?.map((s) => s.replace(/"/g, "")) ?? []
    : ["bd", "pk", "in"];
  map[slug] = countries;
}

const entries = Object.entries(map).sort(([a], [b]) => a.localeCompare(b));
const out = `// AUTO-GENERATED by scripts/gen-localized-slugs.mjs. Do not edit by hand.
// Mirrors the country gate of LOCALIZED_ROUTES so hreflang clusters never
// point at a /{country}/{lang}/{slug} URL that would 404.

export type LocalizedCountry = "bd" | "pk" | "in";

export const LOCALIZED_SLUG_COUNTRIES: Record<string, LocalizedCountry[]> = {
${entries.map(([s, c]) => `  ${JSON.stringify(s)}: [${c.map((x) => `"${x}"`).join(", ")}],`).join("\n")}
};
`;
writeFileSync("src/lib/localized-slugs.ts", out);
console.log("slugs:", entries.length);
